"""
Модификация текста: добавление символа ™ после слов из 6 латинских букв.
"""
import re


def add_trademark(text: str) -> str:
    """
    Добавляет символ ™ после каждого слова ровно из 6 латинских букв.
    Слово — последовательность букв в границах слова (\\b).
    """
    pattern = r"\b([a-zA-Z]{6})\b"
    return re.sub(pattern, r"\1™", text)
